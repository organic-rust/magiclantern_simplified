{
    uint32_t base;
    uint32_t flags;
    uint32_t conn_id;
    uint32_t conn_group;
    uint32_t conn_mask;
    uint32_t pack_base;     /* pack/unpack unit, 0 if none; Canon RMWs +0x24 */
};

