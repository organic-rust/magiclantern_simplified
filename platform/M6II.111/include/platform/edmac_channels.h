/** EDMAC channel map for M6II 1.1.1, decoded from the firmware's own tables
 *  used by Engine::Edmac.c (channel table at 0xE1008944, connection IDs at
 *  0xE1008D6C, names from the interrupt name table at 0xE152B59C).
 *
 *  DIGIC 8 is shared by several cameras, so this map may well apply to them
 *  too, but it has only been checked against this ROM.
 */

/* flags: bit 0 = write channel, bit 1 = read channel.
 * bits 2..5 = size class SS / S / M / L, as in Canon's names. */
#define EDMAC_CHAN_FLAG_WRITE 0x1
#define EDMAC_CHAN_FLAG_READ  0x2

/* conn_id >> 16 indexes the connection routing tables below;
 * 0xFFFFFFFF means the channel has no routable connection.
 * Write channels also carry a group (bits 8..15) and a mask (bits 16..31):
 * Canon's ConnectWrite asserts unless the connection value includes the mask
 * bit, and checks the group if one is passed.  Read channels have neither. */
